"""Exact feature interface of the pinned coenensam predictor, verified on 2026-11-23.

This schema does not calculate features. Values must be generated by an audited
point-in-time adapter; NEVER fill missing rankings or rest days with an invented 0.
"""
from __future__ import annotations
import hashlib
from typing import Literal
from pydantic import BaseModel, ConfigDict, Field

FEATURE_NAMES = (
    'elo_diff','ov_diff','p_elo','form_p1','form_p2','h2h',
    'rest_p1','rest_p2','rank_diff','min_nm','surface_clay','surface_grass',
    'tour_wta','spw_diff','rpw_diff','ace_diff','bps_diff','sos_diff',
)
FEATURE_SCHEMA_HASH=hashlib.sha256('|'.join(FEATURE_NAMES).encode('utf-8')).hexdigest()


class FeatureVector(BaseModel):
    model_config=ConfigDict(extra='forbid', allow_inf_nan=False)
    elo_diff: float
    ov_diff: float
    p_elo: float = Field(ge=0.0, le=1.0)
    form_p1: float = Field(ge=0.0, le=1.0)
    form_p2: float = Field(ge=0.0, le=1.0)
    h2h: float
    rest_p1: float = Field(ge=0.0,le=60.0)
    rest_p2: float = Field(ge=0.0,le=60.0)
    rank_diff: float
    min_nm: int = Field(ge=0)
    surface_clay: Literal[0,1]
    surface_grass: Literal[0,1]
    tour_wta: Literal[0]
    spw_diff: float | None
    rpw_diff: float | None
    ace_diff: float | None
    bps_diff: float | None
    sos_diff: float | None

    def has_missing_profile(self) -> bool:
        return any(getattr(self,k) is None for k in ('spw_diff','rpw_diff','ace_diff','bps_diff','sos_diff'))
